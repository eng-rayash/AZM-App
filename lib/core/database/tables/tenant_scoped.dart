import 'package:drift/drift.dart';

/// AZM — نطاق المستأجر
///
/// كل جدول يحمل بيانات **تخصّ شركة** يخلط هذا الـmixin مع
/// [BaseTableMixin]. وجوده على الجدول يعني: لا يُقرأ صفّ منه ولا يُكتب
/// إلا ضمن شركة محدّدة.
///
/// ما لا يحمله عمدًا:
/// - `Users` — المستخدم عالمي ويملك عضويات في أكثر من شركة؛ ربطه بشركة
///   واحدة يمنع ذلك. علاقته بالشركات في `CompanyMembers`.
/// - `AppSettings` — إعدادات جهاز (السمة، تفعيل الرمز) لا بيانات عمل.
/// - `SecurityLogs` — أحداث تقع قبل اختيار شركة أصلًا (دخول، قفل).
/// - جداول المستأجر نفسها — `Companies` هي الجذر، والثلاثة الباقية
///   تحمل `companySyncId` صراحةً منذ v11.
///
/// ## لماذا nullable محليًا
///
/// العمود قابل للإفراغ في SQLite عمدًا: قواعد المستخدمين القائمة فيها
/// صفوف سابقة على تعدّد المستأجرين، وفرض NOT NULL عليها يتطلّب إعادة
/// بناء ٤١ جدولًا في هجرة واحدة. الهجرة تملأ الصفوف القائمة بشركة
/// محلية افتراضية، وطبقة [TenantScope] تضمن أن كل كتابة جديدة تحمل
/// المعرّف.
///
/// الفرض الحقيقي مكانه الخادم: في PostgreSQL يكون العمود NOT NULL
/// بمفتاح أجنبي، وهناك يقع قرار العزل. إخفاء العنصر في Flutter ليس
/// حماية، وكذلك قيد في قاعدة على جهاز المستخدم.
mixin TenantScoped on Table {
  /// الشركة التي يخصّها الصف — `syncId` من جدول `Companies`.
  TextColumn get companyId => text().nullable()();
}
