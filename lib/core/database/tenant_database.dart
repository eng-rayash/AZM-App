/// AZM — قاعدة لكل مستأجر
///
/// العزل المحلي **حقيقة في نظام الملفات لا انضباط استعلامات**.
///
/// البديل الذي رُفض: إضافة `where companyId = ?` إلى كل استعلام. في
/// هذا المشروع ١٨٠ استعلامًا على ٣٨ ملفًا، وكل استعلام يُكتب مستقبلًا
/// يضيف فرصة نسيان. والنسيان هنا لا يُصدر خطأً — يُصدر بيانات شركة
/// أخرى. اختبار لا يكشفه، ومُصرِّف لا يراه، ولا يظهر إلا حين يشتكي
/// عميل أنه يرى ما ليس له.
///
/// حين يكون لكل شركة ملفها، لا يحتاج الاستعلام إلى مرشّح أصلًا: ما
/// ليس في الملف المفتوح غير موجود. استعلام بلا `where` يعيد بيانات
/// الشركة الحالية وحدها — وهو الصواب لا الثغرة.
///
/// ## ما تكلّفه هذه المقايضة
///
/// عرض يجمع شركتين معًا يحتاج فتح ملفين وضمّ النتائج في Dart. هذا
/// مقصود: الحالة نادرة، وجعلها سهلة يعني جعل التسريب سهلًا.
///
/// ## العلاقة بعمود `company_id`
///
/// العمود المضاف في v12 يبقى: الخادم يحتاجه في حمولة المزامنة، وهو
/// يوثّق لأي شركة يتبع الصفّ حين يُصدَّر أو يُنسخ احتياطيًا. لكنه لم
/// يعد **وسيلة** العزل محليًا، بل أثره.
library;

import '../constants/app_constants.dart';

/// اسم ملف القاعدة للمستأجر [tenantId].
///
/// [personalTenant] يعيد الاسم القديم بلا تغيير — وهذا شرط لا تفصيل:
/// تغييره يجعل التطبيق يفتح ملفًا جديدًا فارغًا ويبدو أن بيانات
/// المستخدم ضاعت، وهي موجودة في ملف لم يعد أحد يفتحه.
String tenantDbName(String tenantId) {
  if (tenantId == personalTenant) return AppConstants.dbName;
  return 'azm_${_safeFileSegment(tenantId)}.db';
}

/// المستأجر الافتراضي: لا شركة نشطة — الوضع الشخصي على هذا الجهاز.
const String personalTenant = 'personal';

/// يحوّل معرّفًا إلى مقطع اسم ملف آمن.
///
/// معرّفات الشركات اليوم UUID، وكلها أحرف آمنة. التنقية دفاع عن
/// المستقبل: معرّف يأتي من الخادم أو من استيراد قد يحمل `/` أو `..`،
/// وحينها يصير اسم الملف مسارًا — وهو عطب يتجاوز العزل إلى الكتابة
/// خارج مجلّد التطبيق.
String _safeFileSegment(String raw) {
  final cleaned = raw.replaceAll(RegExp(r'[^A-Za-z0-9_-]'), '_');

  // معرّف فارغ أو كلّه رموز يصير اسمًا واحدًا لكل الحالات، فتتشارك
  // شركات مختلفة ملفًا واحدًا. الفشل الصريح خير من ذلك.
  if (cleaned.replaceAll('_', '').isEmpty) {
    throw ArgumentError.value(
      raw,
      'tenantId',
      'معرّف المستأجر لا يصلح اسمًا لملف',
    );
  }

  if (cleaned.length <= 64) return cleaned;

  // القصّ وحده كان سيجعل معرّفَين يتشاركان بادئة واحدة يتشاركان
  // الملف — أي التسريب نفسه الذي يمنعه هذا الملف، من باب آخر.
  // البصمة تُبقي الاسم مميّزًا مهما طال الأصل.
  return '${cleaned.substring(0, 52)}_${_fingerprint(raw)}';
}

/// بصمة ثابتة قصيرة — للتمييز لا للأمان.
String _fingerprint(String raw) {
  // FNV-1a: قصيرة، ثابتة عبر التشغيلات، ولا تحتاج حزمة.
  // `hashCode` في Dart لا يضمن الثبات بين الإصدارات، واسم ملف يتغيّر
  // بين إصدارين يعني بيانات تختفي.
  var hash = 0x811c9dc5;
  for (final unit in raw.codeUnits) {
    hash = ((hash ^ unit) * 0x01000193) & 0xFFFFFFFF;
  }
  return hash.toRadixString(36).padLeft(7, '0');
}
